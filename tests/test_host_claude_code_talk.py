class FakeReader:
    def __init__(self, *answers):
        self.answers = list(answers)
        self.asked: list[str] = []

    def read(self, tty):
        self.asked.append(tty)
        return self.answers.pop(0)


class FakeTyper:
    def __init__(self, code="typed"):
        self.code = code
        self.typed: list[tuple[str, str]] = []

    def type(self, tty, text):
        self.typed.append((tty, text))
        return self.code, ""

    def key(self, tty, name):
        self.typed.append((tty, f"<{name}>"))
        return self.code, ""


