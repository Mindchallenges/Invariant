class ScriptedTab:
    """A Terminal tab the answer is typed into: each step it is sent moves the
    screen on, as Claude Code 2.1.330 was seen to, by the script it is given."""

    def __init__(self, screens, script):
        self.screens = list(screens)
        self.script = list(script)
        self.steps: list[tuple[str, tuple[str, ...], str]] = []
        self.reads = 0

    def read(self, tty):
        self.reads += 1
        return "contents", self.screens[0]

    def keys(self, tty, names, text=""):
        self.steps.append((tty, tuple(names), text))
        code, *after = self.script.pop(0) if self.script else ("typed",)
        if after:
            self.screens[0] = after[0]
        return code, ""


def answering(tab, pending, picks, **kw):
    reader = ClaudeCodeTalk(reader=tab, typer=tab, wait=lambda seconds: None, **kw)
    return reader.answer(TalkHostLike(HOST, "ttys004"), pending, picks)


def pending_of(*questions):
    return talk.question_call(ask(*questions)["message"]["content"][0], "2.1.330")


