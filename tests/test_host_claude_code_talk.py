"""Claude Code's side of talking to a session: reading its conversation (ADR-029 inc 1, 2).

``hosts/claude_code_talk`` reads a live window's transcript for the page's
last-message excerpt and its Conversation screen, where each of Claude's tool
calls is one line (increment 2, DEC_ADR_029_D19, D20). The contract differs from the telemetry reader's on one
point, and these tests hold it: the telemetry reader skips what it cannot
parse, because a gap in a report is harmless, while this reader **stops** at
the first shape it does not know, because the page must never show a wrong
"last message" (ADR-029 D11, ruling 11). What it does skip is what it knows is
not the conversation: bookkeeping records, tool results, Claude Code's own
notes in a user entry, a subagent's entries, and the line still being written.
"""

